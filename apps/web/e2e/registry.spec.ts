import { expect, test } from '@playwright/test'
import { randomUUID } from 'node:crypto'

test('authenticated asset registration, view, search, editing, archive and restore', async ({ page, request }, testInfo) => {
  const password = process.env.CRYOL_E2E_PASSWORD
  const username = process.env.CRYOL_E2E_USERNAME
  if (!password || !username) throw new Error('Use a disposable Cryol installation and configure CRYOL_E2E_USERNAME and CRYOL_E2E_PASSWORD.')
  const initial = 'Inventory ' + randomUUID().slice(0, 8)
  const updated = initial + ' updated'

  expect((await request.get('/api/v1/assets')).status()).toBe(401)
  await page.goto('/')
  await page.getByLabel('Username').fill(username)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible()

  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Organization settings' }).click()
  const organizationName = page.getByLabel('Organization name')
  await expect(organizationName).toBeVisible()
  if (!await organizationName.inputValue()) {
    await organizationName.fill('Browser verification')
    await page.getByRole('button', { name: 'Save profile' }).click()
    await expect(page.getByRole('heading', { name: 'Dashboard' })).toBeVisible()
  }

  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Assets', exact: true }).click()
  await page.getByRole('button', { name: 'Add asset' }).click()
  const drawer = page.getByRole('dialog')
  await drawer.getByLabel('Asset name').fill(initial)
  await drawer.getByLabel('Manufacturer').fill('Cryol Test Manufacturer')
  await drawer.getByLabel('Serial number').fill('PW-' + initial.slice(-8))
  await drawer.getByLabel('Purchase date').fill('2025-05-08')
  await page.screenshot({ path: testInfo.outputPath('create-drawer.png') })
  await drawer.getByRole('button', { name: 'Save asset' }).click()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('cell', { name: initial, exact: true })).toBeVisible()

  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+k' : 'Control+k')
  const search = page.getByRole('dialog', { name: 'Search assets' })
  await search.getByRole('textbox').fill(initial)
  await expect(search.getByRole('button', { name: new RegExp(initial) })).toBeVisible()
  await search.getByRole('textbox').press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(drawer.getByRole('heading', { name: initial })).toBeVisible()
  await expect(drawer.getByText('Asset registered')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('asset-details.png') })
  await drawer.getByRole('button', { name: 'Edit asset' }).click()
  await drawer.getByLabel('Asset name').fill(updated)
  await page.keyboard.press('Escape')
  await expect(drawer.getByText('Discard unsaved changes?')).toBeVisible()
  await drawer.getByRole('button', { name: 'Keep editing' }).click()
  await page.evaluate(() => window.history.back())
  await expect(drawer.getByText('Discard unsaved changes?')).toBeVisible()
  await drawer.getByRole('button', { name: 'Keep editing' }).click()
  await drawer.getByRole('button', { name: 'Save asset' }).click()
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('cell', { name: updated, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Filters' }).click()
  await drawer.getByLabel('Manufacturer').fill('Cryol Test Manufacturer')
  await drawer.getByLabel('Purchased from').fill('2025-05-01')
  await drawer.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page).toHaveURL(/manufacturer=/)
  await expect(page.getByRole('cell', { name: updated, exact: true })).toBeVisible()

  await page.getByRole('row').filter({ hasText: updated }).getByRole('button', { name: /^View / }).click()
  await drawer.getByRole('button', { name: 'Archive', exact: true }).click()
  await drawer.getByRole('button', { name: 'Archive asset', exact: true }).click()
  await expect(drawer.getByText('Asset archived', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Restore', exact: true }).click()
  await drawer.getByRole('button', { name: 'Restore asset', exact: true }).click()
  await expect(drawer.getByText('Asset restored', { exact: true })).toBeVisible()
  await drawer.getByRole('button', { name: 'Close panel' }).click()
  await expect(drawer).toBeHidden()
  await expect(page).toHaveURL(/manufacturer=/)
  await page.getByRole('checkbox', { name: 'Select all assets on this page' }).check()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  expect((await downloadPromise).suggestedFilename()).toBe('cryol-assets.csv')
  await page.getByRole('button', { name: 'Clear selection' }).click()
  await page.screenshot({ path: testInfo.outputPath('asset-registry.png') })
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Dashboard' }).click()
  await expect(page.getByRole('link', { name: /Active assets/ })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('dashboard.png') })
})
