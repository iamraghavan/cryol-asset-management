var version = "dev"

type identity struct {
	InstallationID string `json:"installationId"`
	Credential     string `json:"credential"`
	Server         string `json:"server"`
}

type httpFailure int

func (failure httpFailure) Error() string {
	return fmt.Sprintf("inventory server returned HTTP %d", failure)
}

func main() {
	log := slog.New(slog.NewJSONHandler(os.Stderr, nil))
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := run(ctx, log, os.Args[1:]); err != nil && !errors.Is(err, context.Canceled) {
		log.Error("agent stopped", "error", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, log *slog.Logger, args []string) error {
	if len(args) > 0 {
		if args[0] == "check-connection" {
			return checkConnectionCommand(ctx, args[1:], os.Stdout)
		}
		if handled, err := platformCommand(ctx, log, args); handled {
			return err
		}
	}
	return runInventory(ctx, log, args)
}

func runInventory(ctx context.Context, log *slog.Logger, args []string) error {
	return runInventoryWithEnrollment(ctx, log, args, nil)
}

func runInventoryWithEnrollment(ctx context.Context, log *slog.Logger, args []string, suppliedToken []byte) error {
	fs := flag.NewFlagSet("cryol-agent", flag.ContinueOnError)
	server := fs.String("server", "", "Cryol HTTPS server origin")
	caFile := fs.String("ca", "", "PEM file for an internal certificate authority")
	stateDir := fs.String("state-dir", "", "dedicated service-account state directory")
	localHTTP := fs.Bool("local-http", false, "allow HTTP only for a same-machine loopback test")
	showToken := fs.Bool("show-token", false, "show enrollment input in an interactive console")
	interval := fs.Duration("interval", 24*time.Hour, "inventory scan interval")
	if len(args) == 0 {
		return errors.New("usage: cryol-agent setup|enroll|scan|run -server https://HOST -state-dir DIR [-ca file]")
	}
	mode := args[0]
	if err := fs.Parse(args[1:]); err != nil {
		return err
	}
	if (mode != "setup" && mode != "enroll" && mode != "scan" && mode != "run") || fs.NArg() != 0 || *stateDir == "" || *interval < time.Minute {
		return errors.New("choose setup, enroll, scan or run, provide -state-dir and use a scan interval of at least one minute")
	}
	origin, err := parseServerOrigin(*server, *localHTTP)
	if err != nil {
		return err
	}
	base := strings.TrimSuffix(origin.String(), "/")
	client, err := newClient(*caFile)
	if err != nil {
		return err
	}
	if origin.Scheme == "http" {
		transport := client.Transport.(*http.Transport)
		dialer := &net.Dialer{Timeout: 10 * time.Second}
		transport.DialContext = func(ctx context.Context, network, address string) (net.Conn, error) {
			host, port, err := net.SplitHostPort(address)
			if err != nil || !inventory.IsLoopbackHost(host) {
				return nil, errors.New("local HTTP destination is not loopback")
			}
			if host == "localhost" {
				for _, ip := range []string{"127.0.0.1", "::1"} {
					if conn, err := dialer.DialContext(ctx, network, net.JoinHostPort(ip, port)); err == nil {
						return conn, nil
					}
				}
				return nil, errors.New("Cryol is not reachable on localhost")
			}
			return dialer.DialContext(ctx, network, address)
		}
	}
	if err := os.MkdirAll(*stateDir, 0700); err != nil {
		return err
	}
	info, err := os.Stat(*stateDir)
	if err != nil || !info.IsDir() || (runtime.GOOS != "windows" && info.Mode().Perm()&0077 != 0) {
		return errors.New("state directory must be accessible only to the service account")
	}
	unlock, err := lockAgent(filepath.Join(*stateDir, "agent.lock"))
	if err != nil {
		return fmt.Errorf("could not acquire agent state lock: %w", err)
	}
	defer unlock()
	path := filepath.Join(*stateDir, "identity.json")
	raw, readErr := os.ReadFile(path)
	if mode == "enroll" || (mode == "setup" && errors.Is(readErr, os.ErrNotExist)) {
		if readErr == nil {
			return errors.New("this state directory already contains an agent identity")
		}
		if !errors.Is(readErr, os.ErrNotExist) {
			return readErr
		}
		fmt.Fprintln(os.Stderr, "Checking Cryol at", base)
		if err := checkEnrollmentServer(ctx, client, origin); err != nil {
			return err
		}
		token := suppliedToken
		if token == nil {
			fd := int(os.Stdin.Fd())
			if !term.IsTerminal(fd) {
				return errors.New("enrollment requires an interactive terminal")
			}
			var err error
			token, err = promptEnrollmentToken(os.Stdin, os.Stderr, fd, *showToken)
			if err != nil {
				return err
			}
		} else if !validEnrollmentToken(token) {
			return errors.New("enter a valid token generated by the Cryol console")
		}
		defer clear(token)
		id := identity{InstallationID: inventory.NewID(), Server: base}
		request, _ := json.Marshal(map[string]string{"installationId": id.InstallationID})
		body, err := post(ctx, client, base, "enroll", string(bytes.TrimSpace(token)), request)
		if err != nil {
			return err
		}
		var result struct{ Credential string }
		if json.Unmarshal(body, &result) != nil || len(result.Credential) != 43 {
			return errors.New("invalid enrollment response")
		}
		id.Credential = result.Credential
		raw, err = json.Marshal(id)
		if err != nil {
			return err
		}
		if err := atomicWrite(path, raw); err != nil {
			return err
		}
		log.Info("agent enrolled", "installation_id", id.InstallationID)
		if mode == "enroll" {
			return nil
		}
		readErr = nil
	}
	var id identity
	if readErr != nil || json.Unmarshal(raw, &id) != nil || id.Server != base || len(id.Credential) != 43 {
		return errors.New("enroll this state directory with the same server before scanning")
	}
	scan := func() error { return syncInventory(ctx, client, id, *stateDir) }
	if mode == "scan" {
		return scan()
	}
	heartbeat := time.NewTicker(5 * time.Minute)
	defer heartbeat.Stop()
	next := time.NewTimer(0)
	defer next.Stop()
	delay := time.Minute
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-heartbeat.C:
			_, err := post(ctx, client, id.Server, "heartbeat", id.Credential, nil)
			if permanent(err) {
				return err
			}
			if err != nil {
				log.Warn("heartbeat failed", "error", err)
			}
		case <-next.C:
			err := scan()
			if permanent(err) {
				return err
			}
			if err != nil {
				log.Warn("inventory upload pending", "error", err)
				next.Reset(delay + time.Duration(rand.Int64N(int64(delay/4))))
				delay = min(delay*2, time.Hour)
			} else {
				log.Info("inventory synchronized")
				delay = time.Minute
				next.Reset(*interval + time.Duration(rand.Int64N(int64(*interval/10))))
			}
		}
	}
}

func promptEnrollmentToken(in io.Reader, out io.Writer, fd int, visible bool) ([]byte, error) {
	var input []byte
	var err error
	if visible {
		fmt.Fprint(out, "Paste enrollment token (visible), then press Enter: ")
		input, err = bufio.NewReaderSize(in, 128).ReadSlice('\n')
	} else {
		fmt.Fprint(out, "Enrollment token (input hidden), then press Enter: ")
		input, err = term.ReadPassword(fd)
		fmt.Fprintln(out)
	}
	if err != nil || !validEnrollmentToken(input) {
		clear(input)
		return nil, errors.New("paste the full enrollment token from the Cryol console and press Enter")
	}
	return input, nil
}

func validEnrollmentToken(input []byte) bool {
	token := bytes.TrimSpace(input)
	if len(token) != 43 {
		return false
	}
	var decoded [32]byte
	defer clear(decoded[:])
	n, err := base64.RawURLEncoding.Strict().Decode(decoded[:], token)
	return err == nil && n == len(decoded)
}

func parseServerOrigin(value string, localHTTP bool) (*url.URL, error) {
	origin, err := url.Parse(strings.TrimSpace(value))
	if err != nil || (origin.Scheme != "https" && origin.Scheme != "http") || origin.Hostname() == "" || origin.User != nil ||
		(origin.Path != "" && origin.Path != "/") || origin.RawQuery != "" || origin.Fragment != "" || origin.ForceQuery {
		return nil, errors.New("enter the full server URL, such as https://cryol.example.internal:8443")
	}
	if origin.Scheme == "http" && (!localHTTP || !inventory.IsLoopbackHost(origin.Hostname())) {
		return nil, errors.New("use an HTTPS address for the Cryol server")
	}
	return origin, nil
}

func checkConnectionCommand(ctx context.Context, args []string, out io.Writer) error {
	fs := flag.NewFlagSet("check-connection", flag.ContinueOnError)
	server := fs.String("server", "", "Cryol HTTPS address")
	ca := fs.String("ca", "", "optional public CA PEM")
	wizard := fs.Bool("wizard-input", false, "read non-secret connection settings from the setup wizard")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if fs.NArg() != 0 {
		return errors.New("remove unexpected connection-check arguments")
	}
	if *wizard {
		*server = os.Getenv("CRYOL_SETUP_SERVER")
		*ca = os.Getenv("CRYOL_SETUP_CA")
	}
	origin, err := parseServerOrigin(*server, false)
	if err != nil {
		return err
	}
	client, err := newClient(*ca)
	if err != nil {
		return fmt.Errorf("cannot load the Cryol public CA: %w", err)
	}
	var local, remote string
	trace := &httptrace.ClientTrace{GotConn: func(info httptrace.GotConnInfo) {
		local, remote = info.Conn.LocalAddr().String(), info.Conn.RemoteAddr().String()
	}}
	if err := checkEnrollmentServer(httptrace.WithClientTrace(ctx, trace), client, origin); err != nil {
		return err
	}
	fmt.Fprintf(out, "Cryol HTTPS verified and inventory endpoint ready.\r\nServer: %s\r\nConnection: %s to %s\r\n", origin, local, remote)
	return nil
}

func checkEnrollmentServer(ctx context.Context, client *http.Client, origin *url.URL) error {
	ctx, cancel := context.WithTimeout(ctx, 8*time.Second)
	defer cancel()
	request, err := http.NewRequestWithContext(ctx, http.MethodGet, strings.TrimSuffix(origin.String(), "/")+"/api/v1/system/readiness", nil)
	if err != nil {
		return err
	}
	response, err := client.Do(request)
	if err != nil {
		if origin.Scheme == "http" && inventory.IsLoopbackHost(origin.Hostname()) {
			return fmt.Errorf("Cryol is not reachable at %s. This bundle is for the computer running Cryol. For another computer, open Cryol at its LAN HTTPS address and download a new bundle: %w", origin, err)
		}
		var unknownCA x509.UnknownAuthorityError
		var hostMismatch x509.HostnameError
		var certificate x509.CertificateInvalidError
		var dns *net.DNSError
		switch {
		case errors.As(err, &unknownCA):
			return fmt.Errorf("the server certificate issuer is not trusted. Use a Cryol setup with the server's public CA: %w", err)
		case errors.As(err, &hostMismatch):
			return fmt.Errorf("the server certificate does not cover this DNS name or IP address: %w", err)
		case errors.As(err, &certificate):
			return fmt.Errorf("the server certificate is invalid or expired: %w", err)
		case errors.As(err, &dns):
			return fmt.Errorf("This endpoint could not resolve the server name. Check DNS or use the server IP if its certificate covers that IP: %w", err)
		case errors.Is(err, context.DeadlineExceeded):
			return fmt.Errorf("no response from Cryol at %s. Check the endpoint's LAN or VPN route, server port, and network firewall: %w", origin, err)
		case errors.Is(err, syscall.ECONNREFUSED):
			return fmt.Errorf("the server refused the connection at %s. Check that Cryol is listening on that HTTPS port: %w", origin, err)
		}
		return fmt.Errorf("cannot establish a trusted connection to Cryol at %s. Check the address, network access, and server certificate: %w", origin, err)
	}
	defer response.Body.Close()
	var reply struct {
		Status string `json:"status"`
	}
	if response.StatusCode != http.StatusOK || json.NewDecoder(io.LimitReader(response.Body, 8192)).Decode(&reply) != nil || reply.Status != "ready" {
		return fmt.Errorf("the server at %s did not report Cryol readiness (HTTP %d). Open the Cryol console and check System status", origin, response.StatusCode)
	}
	return nil
}

func permanent(err error) bool {
	var failure httpFailure
	return errors.As(err, &failure) && failure >= 400 && failure < 500 && failure != 408 && failure != 429
}

func newClient(caFile string) (*http.Client, error) {
	config := &tls.Config{MinVersion: tls.VersionTLS12}
	if caFile != "" {
		certs, err := os.ReadFile(caFile)
		if err != nil {
			return nil, err
		}
		pool, err := x509.SystemCertPool()
		if err != nil {
			return nil, err
		}
		if !pool.AppendCertsFromPEM(certs) {
			return nil, errors.New("internal CA file has no recognized certificates")
		}
		config.RootCAs = pool
	}
	transport := http.DefaultTransport.(*http.Transport).Clone()
	transport.TLSClientConfig = config
	transport.Proxy = nil
	return &http.Client{Transport: transport, Timeout: 30 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}, nil
}

func post(ctx context.Context, client *http.Client, origin, action, token string, body []byte) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, origin+"/api/agent/v1/"+action, bytes.NewReader(body))
	if err != nil {
		return nil, errors.New("could not construct inventory request")
	}
	req.Header.Set("Authorization", "Bearer "+token)
	req.Header.Set("Content-Type", "application/json")
	response, err := client.Do(req)
	if err != nil {
		return nil, err
	}
	defer response.Body.Close()
	if response.StatusCode < 200 || response.StatusCode >= 300 {
		return nil, httpFailure(response.StatusCode)
	}
	return io.ReadAll(io.LimitReader(response.Body, 8192))
}

func syncInventory(ctx context.Context, client *http.Client, id identity, dir string) error {
	queue := filepath.Join(dir, "pending.json")
	body, err := os.ReadFile(queue)
	if errors.Is(err, os.ErrNotExist) {
		snap, err := collect(ctx)
		if err != nil {
			return err
		}
		body, err = json.Marshal(snap)
		if err != nil {
			return err
		}
		if len(body) > inventory.MaxReportBytes {
			return errors.New("inventory exceeds the upload limit")
		}
		if err := atomicWrite(queue, body); err != nil {
			return err
		}
	} else if err != nil {
		return err
	}
	if _, err := post(ctx, client, id.Server, "inventory", id.Credential, body); err != nil {
		return err
	}
	return os.Remove(queue)
}

func atomicWrite(path string, data []byte) error {
	file, err := os.CreateTemp(filepath.Dir(path), ".cryol-")
	if err != nil {
		return err
	}
	defer os.Remove(file.Name())
	_, writeErr := file.Write(data)
	if writeErr == nil {
		writeErr = file.Sync()
	}
	if err := errors.Join(writeErr, file.Close()); err != nil {
		return err
	}
	return os.Rename(file.Name(), path)
}

func collect(ctx context.Context) (inventory.Snapshot, error) {
	if runtime.GOOS != "windows" && runtime.GOOS != "linux" {
		return inventory.Snapshot{}, errors.New("inventory collection is supported on Windows and Linux")
	}
	hostname, err := os.Hostname()
	if err != nil {
		return inventory.Snapshot{}, err
	}
	s := inventory.Snapshot{Version: 1, RunID: inventory.NewID(), AgentVersion: version, Hostname: hostname,
		OSFamily: runtime.GOOS, Architecture: runtime.GOARCH, LogicalCPUs: runtime.NumCPU(), SoftwareStatus: "unavailable"}
	if interfaces, err := net.Interfaces(); err == nil {
		for _, iface := range interfaces {
			if len(s.Network) >= 256 {
				break
			}
			item := inventory.Adapter{Name: iface.Name, MAC: iface.HardwareAddr.String(), Up: iface.Flags&net.FlagUp != 0}
			if addresses, err := iface.Addrs(); err == nil {
				for _, address := range addresses {
					if _, ok := address.(*net.IPNet); ok && len(item.Addresses) < 128 {
						item.Addresses = append(item.Addresses, address.String())
					}
				}
			}
			s.Network = append(s.Network, item)
		}
	}
	collectPlatform(ctx, &s)
	s.ScannedAt = time.Now().UTC()
	return s, s.Validate(s.ScannedAt)
}
